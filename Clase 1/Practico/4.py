print('Para calcular la superficie y perimetro de un rectangulo porfavor ingrese')
base = float(input('la base en metros:'))
altura = float(input('la altura en metros:'))
superficie = base*altura
perimetro = 2*base+2*altura
print('la superficie es de ', superficie,' metros cuadrados')
print('y el perimetro es de ', perimetro,' metros')
